-- Canonical DDL for dune.ls_collision_fix_log, the audit ledger the item-slot
-- collision reconciler (ops/collision-reconciler/) and the earlier hotbar/backpack
-- dedup passes (ops/hotbar-dedup/) write to.
--
-- WHY THIS FILE EXISTS (2026-08-28): the table has lived in the live DB since the
-- 2026-07-24 hotbar pass (owner already = dune, so a pg_dump does not abort on it),
-- but it had no version-controlled DDL, so a fresh restore / bootstrap could not
-- recreate it and a reader could not see its shape. This is idempotent and matches
-- the live schema exactly, so applying it against the live DB is a no-op.
--
-- Every row records where an item came from and where it was re-slotted to, in the
-- SAME transaction as the UPDATE, which is what makes a reconciler pass reversible.

CREATE TABLE IF NOT EXISTS dune.ls_collision_fix_log (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fixed_at           timestamptz NOT NULL DEFAULT now(),
    owner_id           bigint,           -- owning actor (pawn or totem) id
    item_id            bigint,           -- dune.items.id that moved
    template_id        text,
    src_inventory_id   bigint,
    src_position_index integer,
    dst_inventory_id   bigint,           -- same inventory (re-slot in place)
    dst_position_index integer,
    dst_kind           text              -- 'backpack' | 'worn' | 'hotbar' | 'bank' | 'container'
);

ALTER TABLE dune.ls_collision_fix_log OWNER TO dune;
